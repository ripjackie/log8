import numpy as np

ROMSEL = 0x01
ADR_WE = 0x02
ADR_OE = 0x04

MEMOP0 = 0x10
MEMOP1 = 0x20
MEMOP2 = 0x40
MEMENA = 0x80

MM_OP0 = 0x0100
MM_OP1 = 0x0200
MM_OP2 = 0x0400

CTRL_SRST = 0x0800
CTRL_SINR = 0x1000
CTRL_SDIN = 0x2000
CTRL_SFLG = 0x4000

PC_OP0 = 0x010000
PC_OP1 = 0x020000
PC_OP2 = 0x040000
PC_OP3 = 0x080000
SP_OP0 = 0x100000
SP_OP1 = 0x200000
SP_OP2 = 0x400000
SP_OP3 = 0x800000

MEM_FC = MEMENA|MEMOP2
MEM_FD = MEMENA|MEMOP2|MEMOP0
MEM_FE = MEMENA|MEMOP2|MEMOP1
MEM_FF = MEMENA|MEMOP2|MEMOP1|MEMOP0

MM_E16 = MM_OP1
MM_S16 = MM_OP0
MM_SLO = MM_OP2
MM_SHI = MM_OP2|MM_OP0
MM_ELO = MM_OP2|MM_OP1
MM_EHI = MM_OP2|MM_OP1|MM_OP0

PC_EN   = PC_OP3
PC_INC  = PC_OP2|PC_OP0
PC_DEC  = PC_OP2
PC_LD   = PC_OP1

SP_EN   = SP_OP3
SP_INC  = SP_OP2|SP_OP0
SP_DEC  = SP_OP2
SP_LD   = PC_OP1

insts = np.zeros((2, 8), dtype=np.uint32)

insts[0x00, :3] = [ SP_DEC|MEM_FE|ADR_WE|MM_SLO, MEM_FF|ADR_WE|MM_SHI, MM_E16|PC_LD|ROMSEL ]
insts[0x01, :6] = [ PC_EN|MM_S16, MM_ELO|SP_EN|ADR_OE|SP_DEC, MM_EHI|SP_EN|ADR_OE|SP_DEC, MEM_FC|ADR_WE|MM_SLO, MEM_FD|ADR_WE|MM_SHI, MM_E16|PC_LD|CTRL_SDIN|ROMSEL ]

np.savetxt("microcode1.txt", insts, "%08lx", header="v3.0 hex words plain", comments="")
